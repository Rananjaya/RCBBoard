"""
Generates RCBBoard's app icon as vector drawables: a keycap with Sinhala "අ" and Latin "A".

Vector drawables can't contain text, so the letters are converted to outlines from
Noto Sans Sinhala and Noto Sans (bold), SIL Open Font License 1.1.

Usage (see docs/APP_ICON.md):
    python3 -m venv /tmp/icon-venv && /tmp/icon-venv/bin/pip install fonttools skia-pathops
    /tmp/icon-venv/bin/python tools/app-icon/make_icon.py NotoSansSinhala.ttf NotoSans.ttf
Run it from the repository root. It overwrites the files listed in OUTPUTS below.
"""
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

RES = Path("app/src/main/res")

# Colours (ARGB). NAVY is the previous icon background (values/ic_launcher_colors.xml).
NAVY, NAVY2 = "#FF0F1835", "#FF1B2A63"
KEY, KEY_SHADOW, ACCENT = "#FFFFFFFF", "#FF8EA2E8", "#FF4F46E5"

# Geometry in the 108x108 adaptive icon canvas. Everything stays inside the 66 dp safe zone.
KEYCAP = (29, 28, 79, 78, 11)       # x0, y0, x1, y1, corner radius
SHADOW_OFFSET = 3
SINHALA = ("අ", 54, 55.5, 25)  # character, centre x, centre y, height
LATIN = ("A", 68.5, 37.5, 8.5)


def glyph_path(font_file, char, cx, cy, height):
    """Outline of [char], bold, overlaps removed, scaled to [height] and centred on (cx, cy)."""
    font = instancer.instantiateVariableFont(
        TTFont(font_file), {"wght": 700, "wdth": 100}, overlap=instancer.OverlapMode.REMOVE)
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[ord(char)]
    bounds = BoundsPen(glyphs)
    glyphs[name].draw(bounds)
    xmin, ymin, xmax, ymax = bounds.bounds
    s = height / (ymax - ymin)
    # font units (y up) to icon units (y down)
    transform = (s, 0, 0, -s, cx - s * (xmin + xmax) / 2, cy + s * (ymin + ymax) / 2)
    pen = SVGPathPen(glyphs, lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(pen, transform))
    return pen.getCommands()


def rounded_rect(x0, y0, x1, y1, r):
    return (f"M{x0 + r},{y0}H{x1 - r}A{r},{r} 0 0 1 {x1},{y0 + r}V{y1 - r}A{r},{r} 0 0 1 {x1 - r},{y1}"
            f"H{x0 + r}A{r},{r} 0 0 1 {x0},{y1 - r}V{y0 + r}A{r},{r} 0 0 1 {x0 + r},{y0}Z")


HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
    SPDX-License-Identifier: GPL-3.0-only
    RCBBoard app icon: a keycap with Sinhala "අ" and Latin "A".
    The letters are outlines of Noto Sans Sinhala and Noto Sans (bold), (c) The Noto Project Authors,
    SIL Open Font License 1.1 (licenses/THIRD_PARTY_NOTICES.md).
    Generated by tools/app-icon/make_icon.py, see docs/APP_ICON.md. Do not edit by hand.
-->
"""


def vector(body, size="108dp"):
    return HEADER + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}"
    android:height="{size}"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


def path(data, color, even_odd=False, indent="    "):
    fill = ' android:fillType="evenOdd"' if even_odd else ""
    return f'{indent}<path android:fillColor="{color}"{fill}\n{indent}    android:pathData="{data}" />'


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- RCBBoard app icon (Android 8+), see docs/APP_ICON.md -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_rcb_background" />
    <foreground android:drawable="@drawable/ic_launcher_rcb_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_rcb_monochrome" />
</adaptive-icon>
"""

LEGACY = """<?xml version="1.0" encoding="utf-8"?>
<!-- RCBBoard app icon for Android 5-7.1 (no adaptive icons), see docs/APP_ICON.md -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/{0}" />
</layer-list>
"""


def main(sinhala_font, latin_font):
    sinhala = glyph_path(sinhala_font, *SINHALA)
    latin = glyph_path(latin_font, *LATIN)
    x0, y0, x1, y1, r = KEYCAP
    keycap = rounded_rect(x0, y0, x1, y1, r)
    shadow = rounded_rect(x0, y0 + SHADOW_OFFSET, x1, y1 + SHADOW_OFFSET, r)
    foreground = [(shadow, KEY_SHADOW), (keycap, KEY), (sinhala, NAVY), (latin, ACCENT)]
    background = [("M0,0H108V108H0Z", NAVY), ("M0,108L108,0V108Z", NAVY2)]

    def full_icon(shape):
        # whole icon in one drawable (old Android versions, and in the app): shape, clipped, keycap enlarged
        lines = [path(shape, NAVY), f'    <clip-path android:pathData="{shape}" />', path(background[1][0], NAVY2),
                 '    <group android:pivotX="54" android:pivotY="54" android:scaleX="1.4" android:scaleY="1.4">',
                 *[path(d, c, indent="        ") for d, c in foreground], "    </group>"]
        return vector("\n".join(lines), "48dp")

    outputs = {
        "drawable/ic_launcher_rcb_background.xml": vector("\n".join(path(d, c) for d, c in background)),
        "drawable/ic_launcher_rcb_foreground.xml": vector("\n".join(path(d, c) for d, c in foreground)),
        # themed icons (Android 13+): keycap with the letters cut out; overlaps were removed, so even-odd works
        "drawable/ic_launcher_rcb_monochrome.xml": vector(path(keycap + sinhala + latin, "#FFFFFFFF", True)),
        "drawable/ic_launcher_rcb_full.xml": full_icon(rounded_rect(0, 0, 108, 108, 24)),
        "drawable/ic_launcher_rcb_full_round.xml": full_icon("M54,0A54,54 0 1 1 54,108A54,54 0 1 1 54,0Z"),
        "mipmap-anydpi-v26/ic_launcher.xml": ADAPTIVE,
        "mipmap-anydpi-v26/ic_launcher_round.xml": ADAPTIVE,
        "mipmap-anydpi/ic_launcher.xml": LEGACY.format("ic_launcher_rcb_full"),
        "mipmap-anydpi/ic_launcher_round.xml": LEGACY.format("ic_launcher_rcb_full_round"),
    }
    for name, content in outputs.items():
        (RES / name).parent.mkdir(parents=True, exist_ok=True)
        (RES / name).write_text(content, encoding="utf-8")
        print("wrote", RES / name)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
